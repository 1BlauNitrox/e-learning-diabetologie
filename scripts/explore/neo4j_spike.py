"""Write a Cypher script that loads the prototype graph into Neo4j (docs/0008-graph-tooling.md).

The script uses MERGE, so loading it twice gives the same graph. Paste it into the Neo4j
Query tool (or Browser) of an empty database, then run the queries in queries.cypher.

Usage:
    python scripts/explore/neo4j_spike.py prototype/graph/output/graph.json scripts/explore/output/graph.cypher
"""

import json
import sys
from pathlib import Path


def cypher_value(value):
    """Cypher literal for a JSON value; map keys are backtick-quoted."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return "[" + ", ".join(cypher_value(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"`{k}`: {cypher_value(v)}" for k, v in value.items()) + "}"
    return json.dumps(value, ensure_ascii=False)


def to_cypher(graph):
    """One UNWIND statement per label set and per edge type, so the script stays short.

    Edges carry their index as `key`, so MERGE keeps parallel edges of the same type apart
    (e.g. two CONDITION edges of one fact to the same concept).
    """
    labels = {n["id"]: n["labels"][0] for n in graph["nodes"]}
    lines = ["// Generated by scripts/explore/neo4j_spike.py from prototype/graph/output/graph.json."]
    for label in dict.fromkeys(n["labels"][0] for n in graph["nodes"]):
        lines.append(f"CREATE CONSTRAINT {label.lower()}_id IF NOT EXISTS FOR (n:{label}) REQUIRE n.id IS UNIQUE;")
    groups = {}
    for n in graph["nodes"]:
        groups.setdefault(tuple(n["labels"]), []).append({"id": n["id"], **n["props"]})
    for node_labels, rows in groups.items():
        lines.append(f"UNWIND {cypher_value(rows)} AS row\nMERGE (n:{node_labels[0]} {{id: row.id}})\n"
                     f"SET n = row" + "".join(f", n:{l}" for l in node_labels[1:]) + ";")
    edge_groups = {}
    for i, e in enumerate(graph["edges"]):
        key = (e["type"], labels[e["from"]], labels[e["to"]])
        edge_groups.setdefault(key, []).append({"from": e["from"], "to": e["to"], "key": i, "props": e["props"]})
    for (type_, a, b), rows in edge_groups.items():
        lines.append(f"UNWIND {cypher_value(rows)} AS row\nMATCH (a:{a} {{id: row.from}}), (b:{b} {{id: row.to}})\n"
                     f"MERGE (a)-[r:{type_} {{key: row.key}}]->(b)\nSET r += row.props;")
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 1
    graph = json.loads(Path(argv[1]).read_text(encoding="utf-8"))
    out = Path(argv[2])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(to_cypher(graph), encoding="utf-8", newline="\n")
    print(f"{len(graph['nodes'])} nodes, {len(graph['edges'])} edges -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
